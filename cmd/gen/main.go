package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"os/signal"
	"sort"
	"strings"
	"time"
	"unicode/utf8"

	"gopkg.in/yaml.v3"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	defer stop()

	if _, err := os.Stat("go.mod"); err != nil {
		log.Fatalf("generator must be run from the module root directory (where go.mod is located)")
	}

	version := flag.String("version", "main", "Playwright version tag or branch to fetch the spec from")
	specDir := flag.String("spec-dir", "", "Path to local protocol spec directory (default: checks playwright-reference-projects/playwright/packages/protocol/spec)")
	flag.Parse()

	var allKeys []string
	schemas := make(map[string]any)

	// Determine local spec directory if available
	targetSpecDir := *specDir
	if targetSpecDir == "" {
		defaultLocalDir := "playwright-reference-projects/playwright/packages/protocol/spec"
		if info, err := os.Stat(defaultLocalDir); err == nil && info.IsDir() {
			targetSpecDir = defaultLocalDir
		}
	}

	if targetSpecDir != "" {
		fmt.Printf("Loading protocol specs from local directory: %s\n", targetSpecDir)
		entries, err := os.ReadDir(targetSpecDir)
		if err != nil {
			log.Fatalf("failed to read spec directory: %v", err)
		}

		for _, entry := range entries {
			if !strings.HasSuffix(entry.Name(), ".yml") || entry.IsDir() {
				continue
			}

			filePath := targetSpecDir + "/" + entry.Name()
			data, err := os.ReadFile(filePath)
			if err != nil {
				log.Fatalf("failed to read %s: %v", filePath, err)
			}

			var schema map[string]any
			if err := yaml.Unmarshal(data, &schema); err != nil {
				log.Fatalf("failed to parse %s: %v", entry.Name(), err)
			}

			for k, v := range schema {
				if _, ok := schemas[k]; !ok {
					if vm, ok := v.(map[string]any); ok {
						allKeys = append(allKeys, k)
						schemas[k] = vm
					}
				}
			}
		}
	} else {
		apiURL := fmt.Sprintf("https://api.github.com/repos/microsoft/playwright/contents/packages/protocol/spec?ref=%s", *version)

		client := &http.Client{Timeout: 30 * time.Second}
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, apiURL, nil)
		if err != nil {
			log.Fatalf("failed to build request: %v", err)
		}
		if token := os.Getenv("GITHUB_TOKEN"); token != "" {
			req.Header.Set("Authorization", "Bearer "+token)
		}
		resp, err := client.Do(req)
		if err != nil {
			log.Fatalf("failed to fetch github contents: %v", err)
		}
		defer resp.Body.Close()

		if resp.StatusCode != http.StatusOK {
			body, _ := io.ReadAll(resp.Body)
			log.Fatalf("github api error: %s", string(body))
		}

		type GithubContent struct {
			Name        string `json:"name"`
			DownloadURL string `json:"download_url"`
		}
		var contents []GithubContent
		if err := json.NewDecoder(resp.Body).Decode(&contents); err != nil {
			log.Fatalf("failed to parse github contents: %v", err)
		}

		for _, file := range contents {
			if !strings.HasSuffix(file.Name, ".yml") || file.DownloadURL == "" {
				continue
			}

			data, err := fetchYAML(ctx, client, file.DownloadURL)
			if err != nil {
				log.Fatalf("failed to fetch %s: %v", file.Name, err)
			}

			var schema map[string]any
			if err := yaml.Unmarshal(data, &schema); err != nil {
				log.Fatalf("failed to parse %s: %v", file.Name, err)
			}

			for k, v := range schema {
				if _, ok := schemas[k]; !ok {
					if vm, ok := v.(map[string]any); ok {
						allKeys = append(allKeys, k)
						schemas[k] = vm
					}
				}
			}
		}
	}

	sort.Strings(allKeys)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gen/main.go. DO NOT EDIT.\n")
	buf.WriteString("package protocol\n\n")

	// ProtocolVersion identifies the Playwright spec version used to generate this file.
	buf.WriteString(fmt.Sprintf("// ProtocolVersion identifies the Playwright spec version used to generate this file.\nconst ProtocolVersion = \"%s\"\n\n", *version))

	// Pointers helpers
	buf.WriteString(`
// Float returns a pointer to the given float64.
func Float(v float64) *float64 { return &v }

// Int returns a pointer to the given int.
func Int(v int) *int { return &v }

// String returns a pointer to the given string.
func String(v string) *string { return &v }

// Bool returns a pointer to the given bool.
func Bool(v bool) *bool { return &v }
`)
	buf.WriteString("\n")

	for _, k := range allKeys {
		v, ok := schemas[k].(map[string]any)
		if !ok {
			continue
		}
		typ, _ := v["type"].(string)

		if typ == "object" || typ == "object?" {
			buf.WriteString(fmt.Sprintf("type %s struct {\n", k))
			props, ok := v["properties"].(map[string]any)
			if ok {
				var pKeys []string
				for pk := range props {
					pKeys = append(pKeys, pk)
				}
				sort.Strings(pKeys)
				for _, pk := range pKeys {
					pv := props[pk]
					goTyp := goType(pv, schemas)
					goName := capitalize(strings.ReplaceAll(strings.ReplaceAll(pk, "$", ""), "_", ""))

					// handling omit empty if optional
					jsonTag := pk
					if strings.HasSuffix(fmt.Sprintf("%v", pv), "?") || strings.HasSuffix(goTyp, "?") {
						jsonTag += ",omitempty"
					}

					goTyp = cleanType(goTyp, schemas)
					buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goName, goTyp, jsonTag))
				}
			}
			buf.WriteString("}\n\n")
		} else if typ == "interface" {
			// Generate interface as a struct holding an ID (usually channel owner)
			buf.WriteString(fmt.Sprintf("type %s struct {\n", k))
			buf.WriteString("\tGuid string `json:\"guid\"`\n")
			buf.WriteString("}\n\n")

			// Commands and events usually need input/output structures
			if cmds, ok := v["commands"].(map[string]any); ok {
				var cmdKeys []string
				for ck := range cmds {
					cmdKeys = append(cmdKeys, ck)
				}
				sort.Strings(cmdKeys)
				for _, ck := range cmdKeys {
					cv, _ := cmds[ck].(map[string]any)
					// Generate Request struct
					buf.WriteString(fmt.Sprintf("type %s%sRequest struct {\n", k, capitalize(ck)))
					if params, ok := cv["parameters"].(map[string]any); ok {
						var pKeys []string
						for pk := range params {
							pKeys = append(pKeys, pk)
						}
						sort.Strings(pKeys)
						for _, pk := range pKeys {
							pv := params[pk]
							goTyp := cleanType(goType(pv, schemas), schemas)
							goName := capitalize(strings.ReplaceAll(strings.ReplaceAll(pk, "$", ""), "_", ""))
							jsonTag := pk
							if strings.HasSuffix(fmt.Sprintf("%v", pv), "?") || strings.HasSuffix(fmt.Sprintf("%v", goTyp), "?") {
								jsonTag += ",omitempty"
							}
							buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goName, goTyp, jsonTag))
						}
					}
					buf.WriteString("}\n\n")

					// Generate Response struct
					buf.WriteString(fmt.Sprintf("type %s%sResponse struct {\n", k, capitalize(ck)))
					if returns, ok := cv["returns"].(map[string]any); ok {
						var rKeys []string
						for rk := range returns {
							rKeys = append(rKeys, rk)
						}
						sort.Strings(rKeys)
						for _, rk := range rKeys {
							rv := returns[rk]
							goTyp := cleanType(goType(rv, schemas), schemas)
							goName := capitalize(strings.ReplaceAll(strings.ReplaceAll(rk, "$", ""), "_", ""))
							jsonTag := rk
							if strings.HasSuffix(fmt.Sprintf("%v", rv), "?") || strings.HasSuffix(fmt.Sprintf("%v", goTyp), "?") {
								jsonTag += ",omitempty"
							}
							buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goName, goTyp, jsonTag))
						}
					}
					buf.WriteString("}\n\n")
				}
			}

			if evts, ok := v["events"].(map[string]any); ok {
				var evtKeys []string
				for ek := range evts {
					evtKeys = append(evtKeys, ek)
				}
				sort.Strings(evtKeys)
				for _, ek := range evtKeys {
					ev, _ := evts[ek].(map[string]any)
					buf.WriteString(fmt.Sprintf("type %s%sEvent struct {\n", k, capitalize(ek)))
					if params, ok := ev["parameters"].(map[string]any); ok {
						var pKeys []string
						for pk := range params {
							pKeys = append(pKeys, pk)
						}
						sort.Strings(pKeys)
						for _, pk := range pKeys {
							pv := params[pk]
							goTyp := cleanType(goType(pv, schemas), schemas)
							goName := capitalize(strings.ReplaceAll(strings.ReplaceAll(pk, "$", ""), "_", ""))
							jsonTag := pk
							if strings.HasSuffix(fmt.Sprintf("%v", pv), "?") || strings.HasSuffix(fmt.Sprintf("%v", goTyp), "?") {
								jsonTag += ",omitempty"
							}
							buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goName, goTyp, jsonTag))
						}
					}
					buf.WriteString("}\n\n")
				}
			}
		} else if typ == "enum" {
			// Generate string alias for enum
			buf.WriteString(fmt.Sprintf("type %s string\n", k))
			if literals, ok := v["literals"].([]any); ok {
				buf.WriteString("const (\n")
				for _, lit := range literals {
					litStr := fmt.Sprintf("%v", lit)
					cleanLit := strings.ReplaceAll(litStr, "-", "")
					cleanLit = strings.ReplaceAll(cleanLit, " ", "")
					cleanLit = capitalize(cleanLit)
					if cleanLit == "" {
						continue
					}
					buf.WriteString(fmt.Sprintf("\t%s%s %s = \"%s\"\n", k, cleanLit, k, litStr))
				}
				buf.WriteString(")\n\n")
			}
		}
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Println("Warning: failed to format, saving unformatted:", err)
		formatted = buf.Bytes()
	}

	if err = os.MkdirAll("protocol", 0755); err != nil {
		log.Fatalf("failed to create protocol directory: %v", err)
	}
	err = os.WriteFile("protocol/protocol.go", formatted, 0644)
	if err != nil {
		log.Fatalf("failed to write protocol.go: %v", err)
	}

	fmt.Println("Code generation successful.")
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	r, size := utf8.DecodeRuneInString(s)
	return strings.ToUpper(string(r)) + s[size:]
}

func fetchYAML(ctx context.Context, client *http.Client, url string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, fmt.Errorf("failed to build request: %w", err)
	}
	if token := os.Getenv("GITHUB_TOKEN"); token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(resp.Body)
		return nil, fmt.Errorf("unexpected status %d: %s", resp.StatusCode, body)
	}

	return io.ReadAll(resp.Body)
}

func goType(v any, schemas map[string]any) string {
	switch val := v.(type) {
	case string:
		return val
	case map[string]any:
		typ, _ := val["type"].(string)
		if typ == "array" || typ == "array?" {
			items := goType(val["items"], schemas)
			return "[]" + cleanType(items, schemas)
		}
		if typ == "object" || typ == "object?" {
			return "map[string]any"
		}
		return "any"
	default:
		return "any"
	}
}

func cleanType(t string, schemas map[string]any) string {
	isOpt := strings.HasSuffix(t, "?")
	if isOpt {
		t = t[:len(t)-1]
	}

	switch t {
	case "string":
		if isOpt {
			return "*string"
		}
		return "string"
	case "int":
		if isOpt {
			return "*int"
		}
		return "int"
	case "float":
		if isOpt {
			return "*float64"
		}
		return "float64"
	case "boolean":
		if isOpt {
			return "*bool"
		}
		return "bool"
	case "binary":
		return "[]byte"
	default:
		if strings.HasPrefix(t, "[]") {
			return t // arrays are pointers inherently mostly, or handle inner type
		}
		// Check dynamically if the type exists in the schemas to generate it
		if v, exists := schemas[t]; exists {
			if vm, ok := v.(map[string]any); ok {
				typ, _ := vm["type"].(string)
				if typ == "object" || typ == "object?" || typ == "interface" || typ == "enum" {
					if isOpt {
						return "*" + t
					}
					return t
				}
			}
		}
		// Unmapped complex type fallback (e.g., json, Channel, ConsoleMessage...)
		return "any"
	}
}
